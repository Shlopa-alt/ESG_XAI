/** Ключ для словаря: как в KBRAG, без регистра и лишних пробелов. */
export const conceptKey = (name: string) => name.toLowerCase().split(/\s+/).join(" ").trim();

/** Название для человека: русское, если есть, иначе как в статье. */
export const ruName = (name: string): string => {
  const known = RU[conceptKey(name)];
  if (known) return known;
  // часть понятий в базе уже по-русски, но со строчной буквы
  return /^[а-яё]/.test(name) ? name.charAt(0).toUpperCase() + name.slice(1) : name;
};

